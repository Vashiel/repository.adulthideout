def translate_cyrillic(text):
    if not text:
        return ""
    t = text
    for pattern, repl in RUSSIAN_WORDS_MAP.items():
        t = re.sub(pattern, repl, t, flags=re.I)
    t = "".join(CYRILLIC_TO_LATIN.get(c, c) for c in t)
    return re.sub(r'\s+', ' ', t).strip()
